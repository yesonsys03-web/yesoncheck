def version_key(version):
    """ "1.10.0" → (1, 10, 0). 형식이 아니면 ValueError."""
    if not VERSION_RE.fullmatch(version):
        raise ValueError(f"버전 형식이 아닙니다 (X.Y.Z): {version!r}")
    return tuple(int(part) for part in version.split("."))


def find(version):
    """그 버전의 항목. 없으면 LookupError (지어내지 않음)."""
    for release in RELEASES:
        if release.version == version:
            return release
    raise LookupError(f"release_notes.RELEASES에 {version} 항목이 없습니다 — 배포 전에 맨 위에 더할 것")


def notes_text(version):
    """배포 노트 글(GitHub Release·latest.json의 notes): 첫 줄 요약, 빈 줄, 묶음마다 제목과 `- 항목`."""
    release = find(version)
    parts = [release.summary]
    for title, items in release.groups:
        lines = ([title] if title else []) + [f"- {item}" for item in items]
        parts.append("\n".join(lines))
    return "\n\n".join(parts) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("사용: python -m yesoncheck.release_notes X.Y.Z  (그 버전의 배포 노트를 출력)")
    sys.stdout.write(notes_text(sys.argv[1]))
